"""Emit NDJSON records that exercise Mapper.row_for edge cases: every wire
fixture, then mutations (wrong types, oversize fields, control chars, invalid
UTF-8, health detail strings, bad gzip, bignums, floats in int columns...).
Raw bytes are written as-is so invalid UTF-8 reaches both parsers."""
import base64, copy, gzip, json, sys

fixtures = json.load(open(sys.argv[1]))
out = sys.stdout.buffer
TS = 1767225600.0

def emit(rec):
    out.write(json.dumps(rec, separators=(",", ":"), ensure_ascii=False).encode() + b"\n")

def raw(line: bytes):
    out.write(line + b"\n")

for name, rec in fixtures.items():
    emit(rec)

def mut(t, **changes):
    r = copy.deepcopy(fixtures[t])
    for k, v in changes.items():
        if v is DEL:
            r.pop(k, None)
        else:
            r[k] = v
    emit(r)

