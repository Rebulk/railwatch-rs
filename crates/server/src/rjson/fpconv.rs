fn find_cachedpow10(exp: i32, k: &mut i32) -> Fp {
    let one_log_ten = 0.30102999566398114_f64;
    let approx = (-(exp + NPOWERS) as f64 * one_log_ten) as i32;
    let mut idx = (approx - FIRSTPOWER) / STEPPOWERS;
    loop {
        let current = exp + POWERS_TEN[idx as usize].1 + 64;
        if current < EXPMIN {
            idx += 1;
            continue;
        }
        if current > EXPMAX {
            idx -= 1;
            continue;
        }
        *k = FIRSTPOWER + idx * STEPPOWERS;
        let (frac, exp) = POWERS_TEN[idx as usize];
        return Fp { frac, exp };
    }
}

const FRACMASK: u64 = 0x000F_FFFF_FFFF_FFFF;
const EXPMASK: u64 = 0x7FF0_0000_0000_0000;
const HIDDENBIT: u64 = 0x0010_0000_0000_0000;
const SIGNMASK: u64 = 0x8000_0000_0000_0000;
const EXPBIAS: i32 = 1023 + 52;

const TENS: [u64; 20] = [
    10000000000000000000,
    1000000000000000000,
    100000000000000000,
    10000000000000000,
    1000000000000000,
    100000000000000,
    10000000000000,
    1000000000000,
    100000000000,
    10000000000,
    1000000000,
    100000000,
    10000000,
    1000000,
    100000,
    10000,
    1000,
    100,
    10,
    1,
];

fn build_fp(d: f64) -> Fp {
    let bits = d.to_bits();
    let mut fp = Fp { frac: bits & FRACMASK, exp: ((bits & EXPMASK) >> 52) as i32 };
    if fp.exp != 0 {
        fp.frac += HIDDENBIT;
        fp.exp -= EXPBIAS;
    } else {
        fp.exp = -EXPBIAS + 1;
    }
    fp
}

fn normalize(fp: &mut Fp) {
    while fp.frac & HIDDENBIT == 0 {
        fp.frac <<= 1;
        fp.exp -= 1;
    }
    let shift = 64 - 52 - 1;
    fp.frac <<= shift;
    fp.exp -= shift;
}

fn get_normalized_boundaries(fp: &Fp, lower: &mut Fp, upper: &mut Fp) {
    upper.frac = (fp.frac << 1) + 1;
    upper.exp = fp.exp - 1;
    while upper.frac & (HIDDENBIT << 1) == 0 {
        upper.frac <<= 1;
        upper.exp -= 1;
    }
    let u_shift = 64 - 52 - 2;
    upper.frac <<= u_shift;
    upper.exp -= u_shift;

    let l_shift = if fp.frac == HIDDENBIT { 2 } else { 1 };
    lower.frac = (fp.frac << l_shift) - 1;
    lower.exp = fp.exp - l_shift;
    lower.frac <<= lower.exp - upper.exp;
    lower.exp = upper.exp;
}

fn multiply(a: &Fp, b: &Fp) -> Fp {
    let lomask: u64 = 0x0000_0000_FFFF_FFFF;
    let ah_bl = (a.frac >> 32) * (b.frac & lomask);
    let al_bh = (a.frac & lomask) * (b.frac >> 32);
    let al_bl = (a.frac & lomask) * (b.frac & lomask);
    let ah_bh = (a.frac >> 32) * (b.frac >> 32);
    let mut tmp = (ah_bl & lomask) + (al_bh & lomask) + (al_bl >> 32);
    tmp += 1u64 << 31;
    Fp { frac: ah_bh + (ah_bl >> 32) + (al_bh >> 32) + (tmp >> 32), exp: a.exp + b.exp + 64 }
}

fn round_digit(digits: &mut [u8], ndigits: usize, delta: u64, mut rem: u64, kappa: u64, frac: u64) {
    while rem < frac && delta - rem >= kappa && (rem.wrapping_add(kappa) < frac || frac - rem > rem.wrapping_add(kappa).wrapping_sub(frac)) {
        digits[ndigits - 1] -= 1;
        rem += kappa;
    }
}

fn generate_digits(fp: &Fp, upper: &Fp, lower: &Fp, digits: &mut [u8; 18], k: &mut i32) -> usize {
    let wfrac = upper.frac - fp.frac;
    let mut delta = upper.frac - lower.frac;
    let one_exp = upper.exp;
    let one_frac = 1u64 << (-one_exp);
    let mut part1 = upper.frac >> (-one_exp);
    let mut part2 = upper.frac & (one_frac - 1);

    let mut idx = 0usize;
    let mut kappa = 10i32;
    let mut divp = 10usize;
    while kappa > 0 {
        let div = TENS[divp];
        let digit = (part1 / div) as u32;
        if digit != 0 || idx != 0 {
            digits[idx] = digit as u8 + b'0';
            idx += 1;
        }
        part1 -= digit as u64 * div;
        kappa -= 1;
        let tmp = (part1 << (-one_exp)) + part2;
        if tmp <= delta {
            *k += kappa;
            round_digit(digits, idx, delta, tmp, div << (-one_exp), wfrac);
            return idx;
        }
        divp += 1;
    }

    let mut unit = 18usize;
    loop {
        part2 = part2.wrapping_mul(10);
        delta = delta.wrapping_mul(10);
        kappa -= 1;
        let digit = (part2 >> (-one_exp)) as u32;
        if digit != 0 || idx != 0 {
            digits[idx] = digit as u8 + b'0';
            idx += 1;
        }
        part2 &= one_frac - 1;
        if part2 < delta {
            *k += kappa;
            round_digit(digits, idx, delta, part2, one_frac, wfrac.wrapping_mul(TENS[unit]));
            return idx;
        }
        unit -= 1;
    }
}

fn grisu2(d: f64, digits: &mut [u8; 18], k_out: &mut i32) -> usize {
    let mut w = build_fp(d);
    let mut lower = Fp { frac: 0, exp: 0 };
    let mut upper = Fp { frac: 0, exp: 0 };
    get_normalized_boundaries(&w, &mut lower, &mut upper);
    normalize(&mut w);
    let mut k = 0;
    let cp = find_cachedpow10(upper.exp, &mut k);
    w = multiply(&w, &cp);
    upper = multiply(&upper, &cp);
    lower = multiply(&lower, &cp);
    lower.frac += 1;
    upper.frac -= 1;
    *k_out = -k;
    generate_digits(&w, &upper, &lower, digits, k_out)
}

fn emit_digits(digits: &[u8], mut ndigits: usize, out: &mut String, k: i32, neg: bool) {
    let nd = ndigits as i32;
    let mut exp = (k + nd - 1).abs();

    if k >= 0 && exp < 15 {
        out.push_str(std::str::from_utf8(&digits[..ndigits]).unwrap());
        for _ in 0..k {
            out.push('0');
        }
        out.push_str(".0");
        return;
    }

    if k < 0 && (k > -7 || exp < 10) {
        let offset = nd - k.abs();
        if offset <= 0 {
            out.push_str("0.");
            for _ in 0..(-offset) {
                out.push('0');
            }
            out.push_str(std::str::from_utf8(&digits[..ndigits]).unwrap());
        } else {
            let offset = offset as usize;
            out.push_str(std::str::from_utf8(&digits[..offset]).unwrap());
            out.push('.');
            out.push_str(std::str::from_utf8(&digits[offset..ndigits]).unwrap());
        }
        return;
    }

    ndigits = ndigits.min(18 - neg as usize);
    out.push(digits[0] as char);
    if ndigits > 1 {
        out.push('.');
        out.push_str(std::str::from_utf8(&digits[1..ndigits]).unwrap());
    }
    out.push('e');
    out.push(if k + ndigits as i32 - 1 < 0 { '-' } else { '+' });
    let mut cent = 0;
    if exp > 99 {
        cent = exp / 100;
        out.push((cent as u8 + b'0') as char);
        exp -= cent * 100;
    }
    if exp > 9 {
        let dec = exp / 10;
        out.push((dec as u8 + b'0') as char);
        exp -= dec * 10;
    } else if cent != 0 {
        out.push('0');
    }
    out.push(((exp % 10) as u8 + b'0') as char);
}

/// `JSON.generate(f)` for a finite float. NaN/Infinity are the caller's
/// problem (Ruby raises GeneratorError for them).
pub fn dtoa(d: f64, out: &mut String) {
    let neg = d.to_bits() & SIGNMASK != 0;
    if neg {
        out.push('-');
    }
    if d == 0.0 {
        out.push_str("0.0");
        return;
    }
    let mut digits = [0u8; 18];
    let mut k = 0;
    let n = grisu2(d.abs(), &mut digits, &mut k);
    emit_digits(&digits, n, out, k, neg);
}
