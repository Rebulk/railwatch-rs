//! A line-for-line port of the `fpconv_dtoa` that Ruby's json gem (2.21.2)
//! vendors in ext/json/ext/vendor/fpconv.c, so `JSON.generate(float)` output is
//! byte-identical. It is Grisu2, which is NOT always the shortest round-trip
//! form (1e23 prints as 9.999999999999999e+22), which is why we cannot use
//! Rust's own float formatting here.

const NPOWERS: i32 = 87;
const STEPPOWERS: i32 = 8;
const FIRSTPOWER: i32 = -348;
const EXPMAX: i32 = -32;
const EXPMIN: i32 = -60;

#[derive(Clone, Copy)]
struct Fp {
    frac: u64,
    exp: i32,
}

